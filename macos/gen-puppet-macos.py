#!/usr/bin/env python3
"""Generates crates/audioware/src/types/vanilla/puppet_macos.rs: the PlayerPuppet mirror at the macOS offsets.

The mirror in puppet.rs gives every field of PlayerPuppet the Windows offset (the comment after the field). On macOS the offsets are
different: the dump of the Mac game's RTTI (data/rtti_layout_macos.json of the RED4ext.SDK-macos branches) puts the first PlayerPuppet
property at 0x438 (Windows 0x420) and the last at 0xA04 (Windows 0x90C). Two things move them: ScriptedPuppet is 0x18 bytes bigger, and
the script lock `friendly_devices_hostile_to_enemies_lock` (gameScriptReentrantRWLock) is 0xD0 bytes on the Mac against 0x10, because it
wraps pthread locks there. The dump also lists 6 properties the mirror does not declare (they sit at the end or after the lock).

The generated struct keeps the field list, types and order of the mirror and inserts the padding that puts each field at its Mac offset.
Its base is the Entity mirror, followed by padding up to the first property: the properties of gameObject, gamePuppetBase, gamePuppet and
ScriptedPuppet are not repeated (the ScriptedPuppet mirror of puppet.rs nests them at offsets of its own, its Rust size is 0x500 although
the game's PlayerPuppet properties start at 0x420 on Windows, so it cannot be a base of PlayerPuppet at the game's offsets).
Every offset is asserted at compile time (`offset_of!`), so a wrong padding is a build error, not a wrong read.

usage: gen-puppet-macos.py <puppet.rs> <rtti_layout_macos.json> <out puppet_macos.rs>
"""
import hashlib
import json
import re
import sys

SIZES = {'f32': 4, 'i32': 4, 'u32': 4, 'bool': 1, 'u8': 1, 'CName': 8, 'EntityId': 8, 'TweakDbId': 8, 'DelayId': 8,
         'EngineTime': 8, 'NewMappinId': 8, '[u8; 0x4]': 4}


def size_of(ty):
    if ty in SIZES:
        return SIZES[ty]
    if re.match(r'(Ref|WeakRef|RedArray)<.*>$', ty):
        return 16
    return None  # an enum or a struct: the compiler knows


def norm(name):
    return re.sub(r'[^a-z0-9]', '', name.lower())


def main():
    src_path, json_path, out_path = sys.argv[1:4]
    src = open(src_path).read()
    a = src.index('pub struct PlayerPuppet {')
    b = src.index('\n}\n', a)
    fields = []
    for line in src[a:b].splitlines()[1:]:
        m = re.match(r'\s*pub (\w+): (.+?),\s*// (0x[0-9A-Fa-f]+)', line)
        if m:
            fields.append((m.group(1), m.group(2), int(m.group(3), 16)))
            continue
        m = re.match(r'\s*pub (\w+): (.+?),\s*$', line)
        if m and m.group(1) == 'base':
            continue
        if line.strip():
            raise SystemExit('cannot read the field line: %r' % line)
    data = json.load(open(json_path))
    props = data['classes']['PlayerPuppet']['props']
    by_name = {norm(p['name']): p for p in props}
    md5 = hashlib.md5(open(json_path, 'rb').read()).hexdigest()

    rows = []  # (name, type, windows offset, mac offset)
    for name, ty, woff in fields:
        p = by_name.get(norm(name))
        if p is None:
            raise SystemExit('no property %s in the Mac dump' % name)
        rows.append((name, ty, woff, p['offset']))
    # Mac order must be the mirror order
    offs = [r[3] for r in rows]
    if offs != sorted(offs):
        raise SystemExit('the Mac offsets are not in the mirror order')

    out = []
    w = out.append
    w('// GENERATED by macos/gen-puppet-macos.py from puppet.rs and the Mac RTTI dump (rtti_layout_macos.json, md5 %s). Do not edit.' % md5)
    w('//')
    w('// The macOS twin of `PlayerPuppet` in puppet.rs: the same fields at the offsets the Mac game has. Windows 0x420 is 0x438 here (ScriptedPuppet')
    w('// is 0x18 bigger), the script lock is 0xD0 bytes (Windows 0x10), and the dump lists 6 properties the mirror does not declare. Every offset is')
    w('// asserted below. The offset after each field is the Mac one; the Windows one is the comment in puppet.rs.')
    w('#![allow(clippy::all)]')
    w('')
    w('use red4ext_rs::ScriptClass;')
    w('use red4ext_rs::class_kind::Scripted;')
    w('use red4ext_rs::types::{CName, EngineTime, EntityId, IScriptable, RedArray, Ref, TweakDbId, WeakRef};')
    w('')
    w('use super::{Entity, GameObject};')
    w('use super::puppet::*;')
    w('')
    w('#[repr(C)]')
    w('pub struct PlayerPuppet {')
    w('    pub base: Entity,')
    w('    // gameObject, gamePuppetBase, gamePuppet and ScriptedPuppet: not declared here, only their size matters')
    w('    _pad_base: [u8; 0x%X - std::mem::size_of::<Entity>()],' % rows[0][3])
    prev_end = rows[0][3]  # offset after the pad: the first field
    prev_ty_size = 0
    asserts = []
    for i, (name, ty, woff, moff) in enumerate(rows):
        if i > 0:
            pname, pty, pw, pm = rows[i - 1]
            psz = size_of(pty)
            if pty == 'RwLock':
                psz = moff - pm  # replaced below by a byte array of exactly this size
            if psz is None:
                w('    _pad_%03d: [u8; 0x%X - (0x%X + std::mem::size_of::<%s>())],' % (i, moff, pm, pty))
            else:
                gap = moff - (pm + psz)
                if gap < 0:
                    raise SystemExit('%s: negative gap %d after %s' % (name, gap, pname))
                if gap > 0:
                    w('    _pad_%03d: [u8; 0x%X],' % (i, gap))
        if ty == 'RwLock':
            nxt = rows[i + 1][3]
            w('    pub %s: [u8; 0x%X], // 0x%X (Windows 0x%X, a 0x10 byte RwLock)' % (name, nxt - moff, moff, woff))
        else:
            w('    pub %s: %s, // 0x%X (Windows 0x%X)' % (name, ty, moff, woff))
        asserts.append((name, moff))
    w('}')
    w('')
    w('unsafe impl ScriptClass for PlayerPuppet {')
    w('    const NAME: &\'static str = "PlayerPuppet";')
    w('    type Kind = Scripted;')
    w('}')
    w('')
    w('impl AsRef<IScriptable> for PlayerPuppet {')
    w('    fn as_ref(&self) -> &IScriptable {')
    w('        self.base.as_ref()')
    w('    }')
    w('}')
    w('')
    w('impl AsRef<Entity> for PlayerPuppet {')
    w('    fn as_ref(&self) -> &Entity {')
    w('        &self.base')
    w('    }')
    w('}')
    w('')
    w('const _: () = {')
    w('    use std::mem::offset_of;')
    for name, moff in asserts:
        w('    assert!(offset_of!(PlayerPuppet, %s) == 0x%X);' % (name, moff))
    w('};')
    w('')
    open(out_path, 'w').write('\n'.join(out) + '\n')
    print('%d fields written to %s' % (len(rows), out_path))


main()
